            $key = $order->getBuyer()?->getId();
            if (\array_key_exists($key, self::CUNO_BP_CODES_MAPPING)) {
                ++$orderUpdatedCount;
                $order->setInforLnBusinessPartnerCode(self::CUNO_BP_CODES_MAPPING[$key]);
                $this->entityManager->persist($order);
            }

            // Proceeding flush every 10000 rows
            if (($i % 10000) === 0) {
                $this->entityManager->flush();
            }
            ++$i;
        }

        $this->entityManager->flush();
        $output->writeln(\sprintf('Assigned Business Partner Code to %s orders', $orderUpdatedCount));

        return Command::SUCCESS;
    }
