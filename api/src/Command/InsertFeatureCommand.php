    /**
     * {@inheritdoc}
     */
    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $features = $this->getFeatures();

        if (null !== $input->getOption('feature') && null !== $input->getOption('group')) {
            /** @var string $feature */
            $feature = $input->getOption('feature');
            /** @var string $group */
            $group = $input->getOption('group');
            $features = [[mb_strtoupper($feature), mb_strtoupper($group)]];
        }

        $sql = <<<'SQL'
            INSERT IGNORE INTO feature (name) VALUES (?);
            INSERT IGNORE INTO feature_group (group_id, feature_id)
              SELECT
                user_group.id,
                feature.id
              FROM user_group, feature
              WHERE feature.name = :feature AND user_group.name = :group
            SQL;

        $output->writeln('<info>Starting import</info>');
        foreach ($features as $feature) {
            $stmt = $this->connection->prepare($sql);
            $stmt->executeStatement();
            $output->writeln(implode(' => ', $feature));
        }
        $output->writeln('<info>Feature insertion finished</info>');

        return 0;
    }
