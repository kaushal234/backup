 * $pdftk->stamp(
 *      'filepath/fileToStamp.pdf',
 *      'filepath/stampFile.pdf'
 * );
 * $pdftk->out("result.pdf");
 *
 * </code>
 */
class tldPDFToolKit
{

	const WORKING_PATH = '/tmp';
	public $itsFiles;
	public $itsOutputFile;

	function __construct()
	{

	}


	function addFile($file)
	{
		$e = $this->checkFile($file);
		if (is_string($e)) {
			return $e;
		}
		$this->itsFiles[] = $file;
		return;
	}

	function checkFile($filepath)
	{
		$file = new basicFile($filepath);
		// Check if file exists
		if (!$file->isFile()) {
			return "File $filepath not found";
		}
		// Check extension
		$ext = strtoupper($file->getFileExtension());
		if ($ext !== 'PDF') {
			return "File extension '$ext' not valid";
		}
		// Check MIME
		if ($file->getMime() !== 'application/pdf') {
			return 'File is not a pdf from mime information';
		}
		return true;
	}

	function merge($opt = '')
	{
		// Count files
		if (count($this->itsFiles) < 2) {
			return 'Not enough pdf file to merge';
		}
		// Look for options
		$options = null;
		// Prepare command
		$inFiles = escapeshellcmd(implode(' ', $this->itsFiles));
		$outfile = escapeshellcmd(tempnam(self::WORKING_PATH, 'pdftk')) . '.pdf';
		// Do the merge
		$exec_cmd = "pdftk $inFiles cat output $outfile";
		exec($exec_cmd, $exec_output, $exec_status);
		if ($exec_status <> 0) {
			return 'system exec() command error: ' . var_dump($exec_output);
		}
		// if ok, instance the output file with basicFile
		$this->itsOutputFile = new basicFile($outfile);
		return;
	}

	function stamp($fileToStamp, $fileStamp, $opt = [])
	{
		// Check files
		$e = $this->checkFile($fileToStamp);
		if (is_string($e)) {
			return $e;
		}
		$e = $this->checkFile($fileStamp);
		if (is_string($e)) {
			return $e;
		}
		// Escape command
		$outfile = escapeshellcmd(tempnam(self::WORKING_PATH, 'pdftk')) . '.pdf';
		$fileToStamp = escapeshellcmd($fileToStamp);
		$fileStamp = escapeshellcmd($fileStamp);
		// Look for options
		$mode = 'multistamp';
		$allowed_mode = ['stamp', 'multistamp', 'background', 'multibackground'];
		if (!empty($opt['mode']) && in_array($opt['mode'], $allowed_mode)) {
			$mode = escapeshellcmd($opt['mode']);
		}
		// Do the stamp
		$exec_cmd = "pdftk $fileToStamp $mode $fileStamp output $outfile";
		exec($exec_cmd, $exec_output, $exec_status);
		if ($exec_status <> 0) {
			return 'system exec() command error: ' . var_dump($exec_output);
		}
		// if ok, instance the output file with basicFile
		$this->itsOutputFile = new basicFile($outfile);
		return;
	}

	function stampText($fileToStamp, $text, $opt = [])
	{
		// Create stamp file with the text to use
		$html = <<<EOF
<html>
<head><meta http-equiv="Content-Type" content="text/html; charset=utf-8"></head>
<body><p style="width:100%;margin:0;padding:0;text-align:right;font-size:10px;">$text</p></body>
</html>
EOF;
		$pdf = new tldHTML2PDF($html, ['encoding' => 'utf-8', 'margin' => '5mm', 'background' => false]);
		// Stamp
		return $this->stamp(
			$fileToStamp,
			$pdf->itsConvertedPdfFile->getFilePath(),
			$opt
		);
	}

	function out($newFileName = '')
	{
		$this->itsOutputFile->out($newFileName);
	}

}


class tldBarcode
{

	public $itsString;
	public $itsType;
	public $itsOutputFormat;
	public $itsOptions;
	public $itsImage;

	function __construct($string, $type, $options = '')
	{
		$this->itsString = $string;
		$this->itsType = $type;
		$this->itsOptions = $options;
		$this->itsImage = $this->generate();
	}

	function getSupportedTypes()
	{
		return ['Code39', 'Code128', 'Ean13', 'Int25', 'Postnet', 'Upca', 'Upce'];
	}

	function getSupportedOutputFormats()
	{
		return ['jpg', 'png', 'gif'];
	}

	function generate()
	{
		// Do checks
		if (!in_array($type, self::getSupportedTypes())) {
			$this->itsType = 'Code39';
		}
		if (!in_array($this->itsOptions['output'], self::getSupportedOutputFormats())) {
			$this->itsOptions['output'] = 'png';
		}
		// Look for options
		if (empty($this->itsOptions['height']) || !is_int($this->itsOptions['height'])) {
			$this->itsOptions['height'] = 50;
		}
		if (empty($this->itsOptions['width']) || !is_int($this->itsOptions['width'])) {
			$this->itsOptions['width'] = 100;
		}
		// Return the resource
		return Image_Barcode2::draw(
			$this->itsString,
			$this->itsType,
			$this->itsOptions['output'],
			false, // do not send to browser
			$this->itsOptions['height'],
			$this->itsOptions['width'],
			$this->itsOptions['showText'],
			$this->itsOptions['rotation']
		);
	}

	function getImageBase64()
	{
		ob_start();
		switch ($this->itsType) {
			case 'gif':
				imagegif($this->itsImage);
				break;
			case 'jpg':
				imagejpeg($this->itsImage);
				break;
			case 'png':
			default:
				imagepng($this->itsImage);
				break;
		}
		$imgBase64 = base64_encode(ob_get_contents());
		ob_end_clean();
		imagedestroy($this->itsImage);
		return $imgBase64;
	}

	function out()
	{

	}

	function save()
	{

	}

	function toHtml()
	{
		return <<<EOF
<img src="data:image/{$this->itsOptions['output']};base64,{$this->getImageBase64()}">
EOF;
	}

}


