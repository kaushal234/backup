	{
		if (!is_array($a[0])) {
			$result .= "Menu$i";
			$result .= '=new Array("' . $a[0] . '","' . $a[1] . "\",\"\",$count," . $a[2] . ',' . $a[3] . ");\n";
		} else {
			$j = 0;
			foreach ($a as $item) {
				$k = '';
				$count = '0';
				if ($j == 0) {
					$k = "$i";
					$count = count($a) - 1;
				} else {
					$k = $i . '_' . $j;
				}
				$this->getMenuRec($item, $k, $count, $result);
				$j++;
			}
		}
	}
