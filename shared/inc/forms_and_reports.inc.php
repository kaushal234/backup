/**
 *    Base class for all forms and report classes
 *
 *  All forms and report classes extend from this class and inherit vital info
 *  like the location of the smarty template
 *
 * @package FormsAndReports
 */
class basicFormsAndReports
{
	public $itsTPLPath = 'forms_and_reports';

	//returns the html output after parsing with smarty
	function fetch()
	{
		return;
	}

	//all templates for html forms and objects are in the shared_php_inc folder
	function getSmarty()
	{
		return tldUtils::getSmarty('common');
	}

	//creates an array containing an index of the first characters in rows
	//fields, array containing fields to index
	function createIndex($rows, $field)
	{
		if (count($rows) === 0) {
			return;
		}
		$result = [];
		foreach ($rows as $row) {
			$value = trim(($row[$field] ?? ''));
			if (!in_array($value, $result, true)) {
				$result[] = $value;
			}
		}
		sort($result);
		return $result;
	}

	//returns an index to the same URI
	function fetchIndex($index, $suffix = '')
	{
		$smarty = $this->getSmarty();
		$smarty->assign('index', $index);
		$smarty->assign('suffix', $suffix);
		return $smarty->fetch('forms_and_reports/createIndex.tpl');
	}
}

/**
 *    Associative Array table
 *
 *  Creates a table from an indexed array of associative arrays
 *  like from tldUtils::getSqlToAssocArray() and an associative array of key/value
 *  pairs with the key being field name and the value being the column title.
 *
 * <code>
 * $form = new tldAssocTable( $data,
 *                                array("id"=>"ID","name"=>"Customer Name"),
 *                                $options
 *                            );
 * </code>
 *
 * options is an assoc array:
 * "plain": no colours
 * "no_table": write each line like "key: value", writes as table by default
 *
 * @package FormsAndReports
 */
class tldAssocTable extends basicFormsAndReports
{
    public $itsFields;
    public $itsData;
    public $itsOptions;

    function __construct($data, $fields, $options = [])
	{
		$this->itsFields = $fields;
		$this->itsData = $data;
		$this->itsOptions = $options;
	}

	/**
	 * return the Associative Array Report
	 *
	 * @return string
	 */
	function fetch()
	{
		$smarty = $this->getSmarty();
		$smarty->assign('data', $this->itsData);
		$smarty->assign('fields', $this->itsFields);
		$smarty->assign('options', $this->itsOptions);
		$smarty->assign('title', $this->itsOptions['title'] ?? '');
		return $smarty->fetch($this->itsTPLPath . '/tldAssocTable.tpl');
	}
}


/**
 *    HTML Table Matrix
 *
 *  Creates a table from an indexed array of associative arrays
 *  like from tldUtils::getSqlToAssocArray() and two associative arrays of key/value
 *  pairs with the key being field name and the value being the X row or Y column titles.
 *  Typically used to display COUNT values from a dataset
 *
 * @param array $options
 *        [xItems] array of string fixed list instead of autogenerated
 *        [yItems] array of string fixed list instead of autogenerated
 *      [xFieldLink] string The field on which the link has to be generated for in the column ($x=...)
 *      [yFieldLink] string The field on which the link has to be generated for in the line ($y=...)
 *        [doNotShowTotals] boolean
 *        [doNotShowXTotals] boolean
 *        [doNotShowYTotals] boolean
 *        [doNotFormatCells] boolean
 *        [xItemsReversed] boolean
 *    [yItemsReversed] boolean
 *    [style]
 *        [xItems] array of xItem with associated string style values
 *        [yItems] array of yItem with associated string style values
 *
 * @package FormsAndReports
 */
class tldMatrix extends basicFormsAndReports
{
	public $itsTitle;
	public $itsData;
	private $itsXField;
	private $itsYField;
	private $itsCellField;
	private $itsURL;
	private $itsOptions;

	public function __construct($data, $xField, $yField, $cellField, $url, $title = '', $options = [])
	{
		$this->itsTitle = $title;
		$this->itsData = $data;
		$this->itsXField = $xField;
		$this->itsYField = $yField;
		$this->itsCellField = $cellField;
		$this->itsURL = $url;
		if (isset($options['doNotShowTotals']) && $options['doNotShowTotals'] == true) {
			$options['doNotShowXTotals'] = true;
			$options['doNotShowYTotals'] = true;
		}
		$this->itsOptions = $options;
	}

	/**
	 * return the Matrix Report
	 *
	 * @return string
	 */
	function fetch()
	{
		$xItems = [];
		$yItems = [];

		$smarty = $this->getSmarty();
		$smarty->assign('title', $this->itsTitle);

		if (!count($this->itsData ?? [])) {
			return $smarty->fetch($this->itsTPLPath . '/tldMatrix.tpl');
		}
		$totals = [];
		foreach ($this->itsData as $row) {
			//get distinct headings
			if (!in_array($row[$this->itsXField], $xItems, true)) {
				$xItems[] = $row[$this->itsXField];
				if (isset($this->itsOptions['xFieldLink']) && $this->itsOptions['xFieldLink'] == true) {
					$xItemsLinks[$row[$this->itsXField]] = $row[$this->itsOptions['xFieldLink']];
				}
			}
			if (!in_array($row[$this->itsYField], $yItems, true)) {
				$yItems[] = $row[$this->itsYField];
				if (isset($this->itsOptions['yFieldLink']) && $this->itsOptions['yFieldLink'] == true) {
					$yItemsLinks[$row[$this->itsYField]] = $row[$this->itsOptions['yFieldLink']];
				}
			}
			//populate matrix
			if (isset($this->itsOptions['decimals']) && $this->itsOptions['decimals'] == true) {
				$data[$row[$this->itsXField]][$row[$this->itsYField]] =
					$this->itsOptions['doNotFormatCells'] == true ? $row[$this->itsCellField]
						: number_format($row[$this->itsCellField], 1, '.', '');
			} else {
				$data[$row[$this->itsXField]][$row[$this->itsYField]] =
					(isset($this->itsOptions['doNotFormatCells']) && $this->itsOptions['doNotFormatCells'] == true) ? $row[$this->itsCellField]
						: number_format($row[$this->itsCellField]);
			}
			//calc axis totals
			$totals['Total'][$row[$this->itsXField]] = isset($totals['Total'][$row[$this->itsXField]]) ? $totals['Total'][$row[$this->itsXField]] : 0;
			$totals['Total'][$row[$this->itsXField]] += $row[$this->itsCellField];
			$totals[$row[$this->itsYField]]['Total'] = isset($totals[$row[$this->itsYField]]['Total']) ? $totals[$row[$this->itsYField]]['Total'] : 0;
			$totals[$row[$this->itsYField]]['Total'] += $row[$this->itsCellField];
			//calc grand total
			$totals['Total']['Total'] = isset($totals['Total']['Total']) ? $totals['Total']['Total'] : 0;
			$totals['Total']['Total'] += $row[$this->itsCellField];
			if (isset($this->itsOptions['average_margin_sa2']) && $this->itsOptions['average_margin_sa2'] == true) {
				$totals['Total1'][$row[$this->itsXField]] += $row['total_marg'];
				$totals['Total2'][$row[$this->itsXField]] += $row['total_net'];
				$totals[$row[$this->itsYField]]['Total1'] += $row['total_marg'];
				$totals[$row[$this->itsYField]]['Total2'] += $row['total_net'];
				$totals['Total']['Total1'] += $row['total_marg'];
				$totals['Total']['Total2'] += $row['total_net'];
			}

		}
		if (isset($this->itsOptions['average_margin_sa2']) && $this->itsOptions['average_margin_sa2'] == true) {
			foreach ($xItems as $xItem) {
				$totals['Total'][$xItem] = 0 !== $totals['Total2'][$xItem]
                    ? $totals['Total1'][$xItem] * 100 / $totals['Total2'][$xItem]
                    : 0
                ;
			}
			foreach ($yItems as $yItem) {
				$totals[$yItem]['Total'] = $totals[$yItem]['Total1'] * 100 / $totals[$yItem]['Total2'];
			}
			$totals['Total']['Total'] = $totals['Total']['Total1'] * 100 / $totals['Total']['Total2'];
		}
		//format the numbers
		if (isset($this->itsOptions['decimals']) && $this->itsOptions['decimals'] == true) {
			foreach ($xItems as $xItem) {
				$totals['Total'][$xItem] = number_format($totals['Total'][$xItem], 1, '.', '');
			}
			foreach ($yItems as $yItem) {
				$totals[$yItem]['Total'] = number_format($totals[$yItem]['Total'], 1, '.', '');
			}
			$totals['Total']['Total'] = number_format($totals['Total']['Total'], 1, '.', '');
		} else {
			foreach ($xItems as $xItem) {
				$totals['Total'][$xItem] = number_format($totals['Total'][$xItem]);
			}
			foreach ($yItems as $yItem) {
				$totals[$yItem]['Total'] = number_format($totals[$yItem]['Total']);
			}
			$totals['Total']['Total'] = number_format($totals['Total']['Total']);
		}
		if (isset($this->itsOptions['xItems']) && $this->itsOptions['xItems']) {
			$xItems = $this->itsOptions['xItems'];
		} else {
			if (isset($this->itsOptions['xItemsRawOrder']) && $this->itsOptions['xItemsRawOrder']) {
				// Do no reorder
			} elseif (isset($this->itsOptions['xItemsReversed']) && $this->itsOptions['xItemsReversed']) {
				rsort($xItems);
			} else {
				sort($xItems);
			}
		}
		if (isset($this->itsOptions['yItems']) && $this->itsOptions['yItems']) {
			$yItems = $this->itsOptions['yItems'];
		} else {
			if (isset($this->itsOptions['yItemsRawOrder']) && $this->itsOptions['yItemsRawOrder']) {
				// Do no reorder
			} elseif (isset($this->itsOptions['yItemsReversed']) && $this->itsOptions['yItemsReversed']) {
				rsort($yItems);
			} else {
				sort($yItems);
			}
		}
		$xItemsLinks = empty($xItemsLinks) ? array_combine($xItems, $xItems) : $xItemsLinks;
		$yItemsLinks = empty($yItemsLinks) ? array_combine($yItems, $yItems) : $yItemsLinks;
		$smarty->assign('xItems', $xItems);
		$smarty->assign('yItems', $yItems);
		$smarty->assign('xItemsLink', $xItemsLinks);
		$smarty->assign('yItemsLink', $yItemsLinks);
		$smarty->assign('data', $data);
		$smarty->assign('options', $this->itsOptions);
		$smarty->assign('url', $this->itsURL);
		$smarty->assign('totals', $totals);
		return $smarty->fetch($this->itsTPLPath . '/tldMatrix.tpl');
	}
}

/**
 *    Generates a columnar report from array of data
 *
 *  IMPORTANT NOTE :  By default, Report columnar use the sorttable js library
 *  If, for any reason, we decide to stop using it, delete the class of the columnar tlp file
 *  and delete the line that include the js file "/inc/sortable.js" on intranet.tpl
 *
 * <code>
 * $report = new tldReportColumnar($erp->searchAltPN($pn), $OPTIONS);
 * $OPTIONS (array) :
 *        "xItems" => array("t_item"=>"TLD PN",
 *                          "t_suno"=>"Supplier ID",
 *                          "t_aitc"=>"Alt PN",
 *                          "t_matc"=>"Cost"),
 *        "title"  => "Title",
 *        "showzero"          => TRUE,  to show zero on cells
 *        "showNumberOfRows"  => TRUE,  to show total of data rows
 *        "sortable"          => FALSE, to unuse sorttable librarie and display tip
 *        "showItemNumbers"   => TRUE or reversed, to show sequential number in first column
 *        "stickyHeader"      => TRUE,  to set a fixed header while scrolling the table
 *
 *        "sumTotalsArray"    => array("t_matc"    columns array to show the summed total in the TFOOT ),
 *
 *        "links"             => array("t_item"=>"urltonextpage","confirmPopup"=>"Msg text on popup"),
 *          OR
 *        "links"             => array("t_item"=>array("url"=>"urltonextpage","params"=>array("par1"=>"val1","par2"=>"var2")));
 *
 *      "functions"=>array(
 *           "Delete"=>array(
 *               "url"=>"$php_self?m[0]=parts&m[1]=fav&m[2]=delConf&id=",
 *               "param"=>"id"
 *               ),
 *           "Add"=>array(
 *               "img"=>"/shared/path_icon_add",
 *               "url"=>"$php_self?m[0]=parts&m[1]=search&qty=1&pn=",
 *               "param"=>"fav_pn",
 *               "bypassDisplay" => static function ($params, $lineValues) {
 *                  return empty($lineValues['t_txta']);
 *                }
 *           )
 *      )
 * </code>
 *
 * @package FormsAndReports
 */
class tldReportColumnar extends basicFormsAndReports
{
	private $itsData;
	private $itsOptions;

	public function __construct($data, $options = [])
	{
		$this->itsData = $data;
		$this->itsOptions = $options;
	}

	/**
	 * return the Columnar Report
	 *
	 * @return string
	 */
	public function fetch()
	{
		$smarty = $this->getSmarty();
		if ($this->itsData instanceof tldPagination) {
			$data = $this->itsData->getData();
			$this->itsOptions['is_pagination'] = true;
			$this->itsOptions['sortable'] = true;
			$smarty->assign('pagination', $this->itsData);
		} elseif (isset($this->itsOptions['objects'])) {
			foreach ($this->itsData as $line) {
				$data[] = (array)$line;
			}

		} else {
			$data = $this->itsData;
		}
		$smarty->assign('data', $data ?? []);
		$smarty->assign('options', $this->itsOptions);
		return $smarty->fetch($this->itsTPLPath . '/tldReportColumnar.tpl');
	}
}

/**
 *    Generates a CSV from array of data
 *
 * <code>
 * $report = new tldCSV($erp->searchAltPN($pn),
 *                        array("xItems"=>array(    "t_item"=>"TLD PN",
 *                                        "t_suno"=>"Supplier ID",
 *                                        "t_aitc"=>"Alt PN"
 *                                        ),
 *                        "showTitles"=>true
 *                                )
 *                    );
 *
 * </code>
 *
 * @package FormsAndReports
 */
class tldCSV extends basicFormsAndReports
{
	public $itsData;
	public $itsOptions;

	function __construct($data, $options = '')
	{
		$this->itsData = $data;
		$this->itsOptions = $options;
	}

	function str_from_unicode($str, $out_charset = 'gbk')
	{
		$str = preg_replace_callback('|&#([0-9]{1,5});|', 'tldXLS::unicode2utf8_', $str);
		$str = iconv('UTF-8', $out_charset, $str);
		return $str;
	}

	function unicode2utf8_($c)
	{
		return $this->unicode2utf8($c[1]);
	}

	function unicode2utf8($c)
	{
		$str = '';
		if ($c < 0x80) {
			$str .= $c;
		} else {
			if ($c < 0x800) {
				$str .= chr(0xC0 | $c >> 6);
				$str .= chr(0x80 | $c & 0x3F);
			} else {
				if ($c < 0x10000) {
					$str .= chr(0xE0 | $c >> 12);
					$str .= chr(0x80 | $c >> 6 & 0x3F);
					$str .= chr(0x80 | $c & 0x3F);
				} else {
					if ($c < 0x200000) {
						$str .= chr(0xF0 | $c >> 18);
						$str .= chr(0x80 | $c >> 12 & 0x3F);
						$str .= chr(0x80 | $c >> 6 & 0x3F);
						$str .= chr(0x80 | $c & 0x3F);
					}
				}
			}
		}
		return $str;
	}

	/**
	 * return the CSV Report
	 *
	 * @return string
	 */
	public function fetch()
	{
		$result = '"sep=,"' . "\r\n";

		if (count($this->itsData ?? []) === 0) {
			return '';
		}
		$xItems = $this->itsOptions['xItems'];

		if ($this->itsOptions['showTitles']) {
			$resultLine = '';
			foreach ($xItems as $fieldName => $fieldTitle) {
				$resultLine .= '"' . $fieldTitle . '",';
			}
			$result .= substr($resultLine, 0, -1) . "\r\n";
		}
		if (is_array($xItems)) {
			foreach ($this->itsData as $line) {
				$resultLine = '';
				foreach ($xItems as $fieldName => $fieldTitle) {
					$resultLine .= sprintf('"%s",', $this->clean($line[is_numeric($fieldName) ? $fieldTitle : $fieldName]));
				}
				$result .= substr($resultLine, 0, -1). "\r\n";
			}
		} else {
			foreach ($this->itsData as $line) {
				$resultLine = '';
				foreach ($line as $item) {
					$resultLine .= sprintf('"%s",',$this->clean($item));
				}
				$result .= substr($resultLine, 0, -1). "\r\n";
			}
		}

		return $result;
	}

	public function save($destinationFilepath)
	{
		return (bool) file_put_contents($destinationFilepath, $this->fetch());
	}


	private function clean($a)
	{
		// Clean some special chars
		$badChars = ["\n", "\r\n", "\r", '"'];
		$data = str_replace($badChars, '', $a ?? '');
		// clean slashes
		$data = stripslashes($data);
		// Make sure to set data in UTf-8
		$data = tldXLS::str2utf8($data);
		// In case there is html entities...
		$data = tldXLS::htmlEntityDecode($data);
		// done
		return $data;
	}

	function out($filename = 'data.csv')
	{
		header('Content-Type: application/csv');
		header("Content-Disposition: attachment; filename=\"$filename\"");
		header('Pragma: public');
		header('Cache-Control: must-revalidate, post-check=0, pre-check=0');
		echo $this->fetch();
	}
}


class tldXLS
{

	public $itsData;
	public $itsOptions;
	public $objPHPExcel;

	public function __construct($data, $options = [])
	{
		$this->itsData = $data;
		$this->itsOptions = $options;
		$this->init();
		$this->setLines();
	}

	public function init()
	{
		require_once 'PHPExcel.php';
		$this->objPHPExcel = new PHPExcel();
		if (isset($this->itsOptions['creator']) && !empty($this->itsOptions['creator'])) {
			$this->objPHPExcel->getProperties()->setCreator($this->itsOptions['creator']);
		}
		if (isset($this->itsOptions['title']) && !empty($this->itsOptions['title'])) {
			$this->objPHPExcel->getProperties()->setTitle($this->itsOptions['title']);
		}
		if (!array_key_exists('xItems', $this->itsOptions) && !empty($this->itsData[0])) {
			$this->itsOptions['xItems'] = array_combine(array_keys($this->itsData[0]), array_keys($this->itsData[0]));
		}
		$this->objPHPExcel->setActiveSheetIndex(0);
	}

	public function save($destinationFilepath)
	{
		$objWriter = PHPExcel_IOFactory::createWriter($this->objPHPExcel, 'Excel5');
		$objWriter->save($destinationFilepath);
	}

	public function out($filename = 'data.xlsx')
	{
		$objWriter = PHPExcel_IOFactory::createWriter($this->objPHPExcel, 'Excel2007');
		header('Content-Type: application/vnd.ms-excel');
		header('Content-Disposition: attachment;filename="' . $filename . '"');
		header('Cache-Control: max-age=0');
		$objWriter->save('php://output');
		return;
	}

	public function setLines()
	{
		$line = 1;
		// set titles if applicable
		if (isset($this->itsOptions['showTitles']) && !empty($this->itsOptions['showTitles'])) {
			$this->setLine($line, $this->itsOptions['xItems']);
			$line++;
		}
		// set data content
		foreach ($this->itsData as $k => $lineData) {
			// if xItems are set, use data with same order as xItems
			if (isset($this->itsOptions['xItems']) && is_array($this->itsOptions['xItems']) && !empty($this->itsOptions['xItems'])) {
				$data = [];
				foreach ($this->itsOptions['xItems'] as $key => $val) {
					// check if index xItems exists...
					if (!isset($lineData[$key])) {
						//  if not simulate empty val
						$data[$key] = '';
						continue;
					}
					$data[$key] = $lineData[$key];
				}
				$lineData = $data;
			}
			// create line
			$this->setLine($line, $lineData);
			$line++;
		}
	}

	public function setLine($lineNumber, $lineData)
	{
		$col = 0;
		foreach ($lineData as $key => $val) {
			$this->setCell($lineNumber, $col, $val);
			$col++;
		}
		return;
	}

	public function setCell($lineNumber, $columnNumber, $data)
	{
		global $user;
		// Check formatting data if applicable
		$formating = '';
		// -- case of date
		if ($user instanceof \tldUser) {
			$domain = $user->getDomain();
		} else {
			$domain = null;
		}

		if (!is_array($data) && preg_match("/^\d{4}-\d{2}-\d{2}$/", $data) && $domain === 'tld-europe.com') {
			$dtArray = explode('-', trim($data));
			// transform to excel date if applicable
			if ($data == '0000-00-00') {
				$data = '';
			} else {
				$data = PHPExcel_Shared_Date::FormattedPHPToExcel($dtArray[0], $dtArray[1], $dtArray[2]);
				$formating = 'FORMAT_DATE_DMYSLASH';
			}
		}

		if(!is_numeric($data) || (is_numeric($data) && strlen($data) > 10)){
			$formating = 'TYPE_STRING';
		}

		// Make sure to set data in UTf-8
		$data = self::str2utf8($data);
		// In case there is html entities...
		$data = self::htmlEntityDecode($data);

		// Look for style formatting
		switch ($formating) {
			case 'FORMAT_DATE_DMYSLASH':
				// update style and formatting
				$this->objPHPExcel->getActiveSheet()->setCellValueByColumnAndRow($columnNumber, $lineNumber, $data);
				$this->objPHPExcel->getActiveSheet()
					->getStyleByColumnAndRow($columnNumber, $lineNumber)
					->getNumberFormat()
					->setFormatCode(PHPExcel_Style_NumberFormat::FORMAT_DATE_DMYSLASH);
				break;
			case 'TYPE_STRING':
				$this->objPHPExcel
					->getActiveSheet()
					->setCellValueExplicitByColumnAndRow($columnNumber, $lineNumber, $data, PHPExcel_Cell_DataType::TYPE_STRING);
				break;
			default:
				$this->objPHPExcel->getActiveSheet()->setCellValueByColumnAndRow($columnNumber, $lineNumber, $data);
				break;
		}
		return;
	}

	public static function htmlEntityDecode($str)
	{
		return html_entity_decode($str, ENT_COMPAT | ENT_HTML401, 'UTF-8');
	}

	public static function str2utf8($str)
	{
		$possibleEncodingList = ['UTF-8', 'ISO-8859-1', 'CP936'];
		$encodingDetected = mb_detect_encoding($str, $possibleEncodingList, true);
		// if encoding detected, convert to utf8
		if ($encodingDetected !== 'UTF-8' && $encodingDetected !== false) {
			$str = iconv($encodingDetected, 'UTF-8', $str);
		}
		return $str;
	}

}

/**
 * Generates a multi level report
 *
 * <code>
 *  EXAMPLE:
