	{
		return ['division', 'subdivision', 'region', 'bu', 'department', 'function'];
	}

	function getArrayFromPost($post)
	{
		// Dimensions
		$dimList = self::getOrgDimensionList();
		// Counting lines to add
		$nbLinesToAdd = 1;
		foreach ($dimList as $dim) {
			// if no data, add one entry NULL (id=0)
			if (empty($post[$dim])) {
				$post[$dim][] = 0;
			}
			// calculate total rules to create
			$nbLinesToAdd = $nbLinesToAdd * count($post[$dim]);
		}
		// Assigning data to lines per dimensions
		$toAdd = [];
		foreach ($post['division'] as $division) {
			foreach ($post['subdivision'] as $subdivision) {
				foreach ($post['region'] as $region) {
					foreach ($post['bu'] as $bu) {
						foreach ($post['department'] as $department) {
							foreach ($post['function'] as $function) {
								$entities = [
									'division' => $division,
									'subdivision' => $subdivision,
									'region' => $region,
									'bu' => $bu,
								];
								foreach ($entities as $type => &$value) {
									if ($type !== $post['type']) {
										$value = 0;
									}
								}
								$positions = [
									'department' => $department,
									'function' => $function,
								];

								$toAdd[] = $entities + $positions;
							}
						}
					}
				}
			}
		}

		return $toAdd;
	}

}

/**
 * Class for converting html to pdf
 * @package FormsAndReports
 *
 * More info --> http://code.google.com/p/wkhtmltopdf/
 * Manual --> http://madalgo.au.dk/~jakobt/wkhtmltoxdoc/wkhtmltopdf_0.10.0_rc2-doc.html
 *
 * <code>
 *   $OPTIONS = array(
 *      encoding    => the encoding you need (utf-8,iso-XXXXX,GBXXXXX)
 *      margin      => in mm (default 10mm)
 *      title       => string title (default none)
 *      pagesize    => A4 or Letter (default A4)
 *      orientation => Landscape or Portrait (default Portrait)
 *   );
 *
 *   Options below forced in command:
 *      --lowquality
 *      --disable-javascript
 *
 * </code>
 */
class tldHTML2PDF
{

	public $itsHtml;
	public $itsOptions;
	public $itsHtmlTempFile;
	/** @var basicFile */
	public $itsConvertedPdfFile = null;

	public function __construct($string, $options = '')
	{
		$this->itsHtml = $string;
		$this->itsOptions = $options;
		$e = $this->convert();
		if (is_string($e)) {
			error_log("tldHTML2PDF::__construct() error -> $e");
			echo $e;
		}
	}

	/**
	 * Convert HTML string into a PDF file
	 * @return string on error
	 */
	public function convert()
	{
		// Create html file
		$e = $this->createHtmlFile();
		if (is_string($e)) {
			return $e;
		}
		// Protect commands by parsing arguments
		$infile = escapeshellcmd($this->itsHtmlTempFile->getFilePath());
		$outfile = escapeshellcmd(tempnam('/tmp', 'html2pdf')) . '.pdf';
		// Look for options
		$options = null;
		// Page Margin
		$margin = '10mm';
		if (!empty($this->itsOptions['margin'])) {
			$margin = escapeshellarg($this->itsOptions['margin']);
		}
		$options = " --margin-bottom $margin --margin-left $margin --margin-right $margin --margin-top $margin";
		// Page orientation
		$orientation = 'Portrait';
		if (!empty($this->itsOptions['orientation'])) {
			$orientation = escapeshellarg($this->itsOptions['orientation']);
		}
		$options .= " --orientation $orientation";
		// Page size
		$pagesize = 'A4';
		if (!empty($this->itsOptions['pagesize'])) {
			$pagesize = escapeshellarg($this->itsOptions['pagesize']);
		}
		$options .= " --page-size $pagesize";
		// Background
		$background = ' --background';
		if (!isset($this->itsOptions['background']) || $this->itsOptions['background'] === false) {
			$background = ' --no-background';
		}
		$options .= " $background";
		// Title
		if (!empty($this->itsOptions['title'])) {
			$options .= ' --title ' . escapeshellarg($this->itsOptions['title']);
		}
		// Encoding
		if (!empty($this->itsOptions['encoding'])) {
			$options .= ' --encoding ' . escapeshellarg($this->itsOptions['encoding']);
		}

		if (!empty($this->itsOptions['footer'])) {
			$options .= ' --footer-right ' . escapeshellarg($this->itsOptions['footer']);
		}
		// Convert and create PDF file
		$exec_cmd = "/usr/local/bin/wkhtmltopdf --lowquality --disable-javascript $options $infile $outfile";
		// For local use
		//$exec_cmd = "xvfb-run -a wkhtmltopdf --lowquality --disable-javascript $options $infile $outfile";
		exec($exec_cmd, $exec_output, $exec_status);
		if ($exec_status <> 0) {
			$err = implode(', ', (array)$exec_output);
			return 'system exec() command error: ' . $err;
		}
		// assign converted file as basicFile object
		$this->itsConvertedPdfFile = new basicFile($outfile);
		return;
	}

	/**
	 * Create temp file from html string
	 * @return string on error
	 */
	private function createHtmlFile()
	{
		// create temp files
		$filename = tempnam('/tmp', 'html2pdf');
		// create basic file object
		$this->itsHtmlTempFile = new basicFile($filename);
		if (!$this->itsHtmlTempFile->isFile()) {
			return "The file $filename was not created";
		}
		// rename to have html extension (htmldoc v 1.8.27 requires it)
		$this->itsHtmlTempFile->rename(
			$this->itsHtmlTempFile->getBasename() . '.html'
		);
		$filename = $this->itsHtmlTempFile->getFilePath();
		// check if file is ok
		if (!$this->itsHtmlTempFile->isWritable()) {
			return "The file $filename is not writable";
		}
		// try to open it
		if (!$handle = fopen($filename, 'a')) {
			return "Cannot open file ($filename)";
		}
		// look for options
		// --- update http references (links)
		if (!empty($this->itsOptions['links'])) {
			$this->itsHtml = str_replace(
				$this->itsOptions['links']['baseurl'],
				$this->itsOptions['links']['basedir'],
				$this->itsHtml
			);
		}
		// write in temp file
		if (fwrite($handle, $this->itsHtml) === false) {
			return "Cannot write to file ($filename)";
		}
		// close file
		fclose($handle);
		// return
		return;
	}

	/**
	 * Get converted pdf file object
	 * @return basicFile|null instance
	 */
	public function getFile()
	{
		return $this->itsConvertedPdfFile;
	}

	/**
	 * Send converted file to stdout
	 * @param string|null $file Final filename to use at client side
	 */
	public function outFile($file = '')
	{
	    if (null === $this->itsConvertedPdfFile) {
	        return null;
        }

		return $this->itsConvertedPdfFile->out($file);
	}
}

/**
 *
 * Class for manipulating pdf file
 * @package FormsAndReports
 *
 * More info --> http://www.pdflabs.com/tools/pdftk-the-pdf-toolkit/
 *
 * Examples:
 * <code>
 * // Initialise the class tool
 * $pdftk = new tldPDFToolKit();
 *
