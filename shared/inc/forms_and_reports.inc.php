	{
		if (!is_array($this->itsMenu)) {
			return;
		}
		$smarty = $this->getSmarty();
		$menu = '';
		$i = 1;
		foreach ($this->itsMenu as $item) {
			$this->getMenuRec($item, $i, 0, $menu);
