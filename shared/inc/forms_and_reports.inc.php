class tldOverlib extends basicFormsAndReports
{

	public $itsText;

	function __construct($text, $options = '')
	{
		$this->itsText = $this->cleanText($text);
		$this->itsOptions = $options;
	}

	function cleanText($text)
	{
		// Clean line return
		$nallow = ["\r", "\n"];
		$text = str_replace($nallow, '', $text);
		// Clean html
		$text = htmlentities($text);
		// clean quotes
		$text = TldDatabase::escape($text);
		// Clean special char
		$nallow = ['>', '<'];
		$text = str_replace($nallow, '', $text);
		return $text;
	}

	/**
	 * return the "overlib" string
	 * @return string
	 */
	function fetch()
	{
		$smarty = $this->getSmarty();

		// if there is a link name specified use it, else use "Over Here"
		if ($this->itsOptions['linkName']) {
			$linkName = $this->itsOptions['linkName'];
		} else {
			$linkName = 'Over Here';
		}
		$vars = '';
		// check if the CAPTION is specified in the Options
		if ($this->itsOptions['CAPTION']) {
			$vars .= ",CAPTION,'{$this->itsOptions['CAPTION']}'";
		}

		// check if the WIDTH is specified in the Options
		if ($this->itsOptions['WIDTH']) {
			$vars .= ",WIDTH,'{$this->itsOptions['WIDTH']}'";
		} else {
			$vars .= ',WIDTH,250';
		}

		// check if the OFFSETX is specified in the Options, default "OFFSETX,50""
		if ($this->itsOptions['OFFSETX']) {
			$vars .= ",OFFSETX,'{$this->itsOptions['OFFSETX']}'";
		} else {
			$vars .= ',OFFSETX,50';
		}

		// check if the VAUTO = OFF is specified in the Options, default "VAUTO"
		if (($this->itsOptions['VAUTO'] ?? null) !== 'OFF') {
			$vars .= ',VAUTO';
		}

		// check if the FGCOLOR is specified in the Options, by default uses "FGCOLOR, '#eeeeee'"
		if ($this->itsOptions['FGCOLOR'] ?? null) {
			$vars .= ",FGCOLOR,'{$this->itsOptions['FGCOLOR']}'";
		} else {
			$vars .= ",FGCOLOR,'#eeeeee'";
		}

		// check if the BGCOLOR is specified in the Options, by default uses "BGCOLOR, 'gray'"
		if ($this->itsOptions['BGCOLOR'] ?? null) {
			$vars .= ",BGCOLOR,'{$this->itsOptions['BGCOLOR']}'";
		} else {
			$vars .= ",BGCOLOR,'gray'";
		}

		// check if the CAPCOLOR is specified in the Options by default uses "CAPCOLOR, '#dedede'"
		if ($this->itsOptions['CAPCOLOR'] ?? null) {
			$vars .= ",CAPCOLOR,'{$this->itsOptions['CAPCOLOR']}'";
		} else {
			$vars .= ",CAPCOLOR,'#dedede'";
		}

		$result = "<a href=\"javascript:void(0);\" onMouseOver=\"javascript:overlib('" . $this->itsText . "'" . $vars . ');" onMouseOut="javascript:nd();">' . $linkName . '</a>';
		return $result;
	}
}


class tldTagCloud
{
	function __construct()
	{
		$this->itsTags = [];
		$this->itsMax = 0;
		$this->itsMin = 0;
		$this->itsMinSize = 9;
		$this->itsMaxSize = 48;
	}

	function addTag($tag, $weight, $url = '')
	{
		if ($weight == 0) {
			return;
		}
		if ($weight > $this->itsMax || $this->itsMax == 0) {
			$this->itsMax = $weight;
		} elseif ($weight < $this->itsMin || $this->itsMin == 0) {
			$this->itsMin = $weight;
		}
		$this->itsTags[$tag] = [
			'weight' => $weight,
			'url' => $url,
		];
	}

	function fetch()
	{
		if (count($this->itsTags) == 0) {
			return;
		}
		$r = '';
		foreach ($this->itsTags as $tag => $row) {
			if ($this->itsMax - $this->itsMin == 0) {
				$size = $this->itsMinSize;
			} else {
				$size = floor($this->itsMinSize +
					(
						($this->itsMaxSize - $this->itsMinSize) * ($row['weight'] - $this->itsMin) /
						($this->itsMax - $this->itsMin)
					)
				);
			}
			$r .= '<a ' . (empty($row['url']) ? '' : "href='" . $row['url'] . urldecode($tag) . "' ") . "style='font-size:{$size}px'>$tag</a>";
		}
		return $r;
	}


}


