/**
 * Class to create graph
 * Using HIGHCHART JS
 *
 * <code>
 * try
 * {
 *     $graph = new tldGraph();
 *     $graph->setTitle('Test chart');
 *     $graph->setYAxisTitle('Temperature');
 *     $graph->setXAxisTitle('Month');
 *     $graph->setXAxisCategories(array('Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'));
 *     $graph->addBar(
 *         array(7.0, 6.9, 9.5, 14.5, 18.4, 21.5, 25.2, 26.5, 23.3, 18.3, 13.9, 9.6),
 *         array('name'=>'Tokyo')
 *     );
 *     $graph->addBar(
 *         array(3.9, 4.2, 5.7, 8.5, 11.9, 15.2, 17.0, 16.6, 14.2, 10.3, 6.6, -4.8),
 *         array('name'=>'London')
 *     );
 *     $graph->addGroupTarget(16);
 *     $body.= $graph->fetch();
 * }
 * catch (Exception $e)
 * {
 *     $DEFAULT_ERROR[] = "ERROR: An issue occurred during graph creation. Details: ".$e->getMessage();
 * }
 * </code>
 */
class tldGraph
{

	protected $parameters;

	public function setTitle($title)
	{
		$this->parameters['title']['text'] = $title;
	}

	public function setYAxisTitle($title)
	{
		$this->parameters['yAxis']['title']['text'] = $title;
	}

	public function setYAxisMaxValue($val)
	{
		$this->parameters['yAxis']['max'] = $val;
	}

	public function setYAxisFloorValue($val)
	{
		$this->parameters['yAxis']['floor'] = $val;
	}

	public function setMultipleYAxisTitle($title, $options = [])
	{
		$this->parameters['yAxis'][] = array_replace(
			[
				'title' => ['text' => $title],
			],
			$options
		);
	}

	public function setXAxisTitle($title)
	{
		$this->parameters['xAxis']['title']['text'] = $title;
	}

	public function addXAxisOptions($options)
	{
		$this->parameters['xAxis'] = array_replace(
			$this->parameters['xAxis'] ?: [],
			$options
		);
	}

	public function addYAxisOptions($options)
	{
		$this->parameters['yAxis'] = array_replace(
			$this->parameters['yAxis'] ?: [],
			$options
		);
	}

	public function setTooltip($values, $options = [])
	{
		$this->parameters['tooltip'] = array_replace(
			[
				'enabled' => $values,
			],
			$options);
	}

	public function addChartOptions($options)
	{
		$this->parameters['chart'] = array_replace(
			$this->parameters['chart'] ?: [],
			$options
		);
	}

	public function setXAxisCategories($categories)
	{
		$this->parameters['xAxis']['categories'] = $categories;
	}

	public function getXAxisCategories()
	{
		return $this->parameters['xAxis']['categories'];
	}

	public function addSeries($values, $options = [])
	{
		$this->parameters['series'][] = array_replace(
			[
				'data' => $values,
			],
			$options
		);
	}

	public function addNamedSerie($name, $values, $options = [])
	{
		$this->parameters['series'][] = array_replace(
			[
				'name' => $name,
				'data' => $values,
			],
			$options
		);
	}

	public function addBar($values, $options = [])
	{
		$this->parameters['series'][] = array_replace(
			[
				'type' => 'column',
				'data' => $values,
				'dataLabels' => [
					'enabled' => true,
					'allowOverlap' => true,
				],
				'enableMouseTracking' => false,
			],
			$options
		);
	}

	public function addLine($values, $options = [])
	{
		$this->parameters['series'][] = array_replace(
			[
				'type' => 'line',
				'data' => $values,
				'dataLabels' => [
					'enabled' => true,
					'allowOverlap' => true,
				],
				'enableMouseTracking' => false,
			],
			$options
		);
	}

	public function addScatter($values, $options = [])
	{
		$this->parameters['series'][] = array_replace(
			[
				'type' => 'scatter',
				'data' => $values,
				'marker' => ['radius' => 8],
				'dataLabels' => [
					'enabled' => true,
					'allowOverlap' => true,
				],
				'enableMouseTracking' => false,
			],
			$options
		);
	}

	public function addGroupTarget($val)
	{
		// Generate values from X categories
		$values = [];
		$xAxisCat = $this->getXAxisCategories();
		if (isset($xAxisCat) && !empty($xAxisCat)) {
			foreach ($xAxisCat as $v) {
				$values[] = $val;
			}
		} else {
			throw new Exception('Can not create Group Target, XAxis categories must be set');
		}
		// Prepare options
		$options = [
			'name' => "Group Target ($val)",
			'color' => 'red',
			'dataLabels' => ['enabled' => false],
			'marker' => ['enabled' => false],
			'enableMouseTracking' => false,
		];
		// Add group target line
		$this->addLine($values, $options);
	}

	protected function checkDataSerie($data)
	{
		$countDataEl = count($data ?? []);
		$countCategoriesEl = count($this->getXAxisCategories());
		// check if data elements match Xaxis elements
		if ($countDataEl != $countCategoriesEl) {
			throw new Exception("Data elements provided ($countDataEl) do not match number of X axis categories elements ($countCategoriesEl)");
		}
	}

	protected function encodeParameters()
	{
		return htmlentities(json_encode($this->parameters, JSON_PARTIAL_OUTPUT_ON_ERROR));
	}

	public function fetch($id = null)
	{
		if ($id !== null) {
			return <<<EOF
<div id="$id" class="tldGraph" data-tldgraph="{$this->encodeParameters()}"></div>
EOF;
		}
		return <<<EOF
<div class="tldGraph" data-tldgraph="{$this->encodeParameters()}"></div>
EOF;
	}

}


class tldGraphGeneric
{

	public $itsGraph;
	public $itsOptions;
	public $itsPlotArea;
	public $itsLegend;

	function __construct($options)
	{
		include_once 'Image/Graph.php';
		$this->initOptions($options);
		$this->initGraph();
	}

	private function initOptions($options)
	{
		// Assign options
		$this->itsOptions = $options;
		// Check missing options & default values
		// -- Title text & size
		if (empty($this->itsOptions['title'])) {
			$this->itsOptions['title'] = 'Graph title';
		}
		if (empty($this->itsOptions['titleSize'])) {
			$this->itsOptions['titleSize'] = 14;
		}
		// -- graph size
		if (empty($this->itsOptions['width'])) {
			$this->itsOptions['width'] = 980;
		}
		if (empty($this->itsOptions['height'])) {
			$this->itsOptions['height'] = 500;
		}
		// -- Font text
		if (empty($this->itsOptions['font'])) {
			$this->itsOptions['font'] = 'DejaVuLGCSans-Bold';
		}
		if (empty($this->itsOptions['fontSize'])) {
			$this->itsOptions['fontSize'] = 10;
		}
		if (empty($this->itsOptions['fontColor'])) {
			$this->itsOptions['fontColor'] = 'black';
		}
	}

	private function initGraph()
	{
		// Create main container
		$this->itsGraph = &Image_Graph::factory('graph', [
			$this->itsOptions['width'],
			$this->itsOptions['height'],
		]);
		// Padding
		$this->itsGraph->setPadding(20);
		// Set font
		$Font =& $this->itsGraph->addNew('ttf_font', $this->itsOptions['font'] . '.ttf');
		$Font->setSize($this->itsOptions['fontSize']);
		$Font->setColor($this->itsOptions['fontColor']);
		$this->itsGraph->setFont($Font);
        $plotArea = Image_Graph::factory('plotarea');
        $legend = Image_Graph::factory('legend');

		// Create graph structure and contents
		$this->itsGraph->add(
		// Vertical structure
			Image_Graph::vertical(
			// Title
				Image_Graph::factory('title', [
					$this->itsOptions['title'],
					$this->itsOptions['titleSize'],
				]),
				// Plotarea + Legend
				Image_Graph::vertical(
                    $plotArea,
					$legend,
					90 // take 90 % for plotarea
				),
				10 // take 5 % for title
			)
		);

		// Display legend of plotarea
		$legend->setPlotarea($this->itsPlotArea);

		// Create horizontal scale lines
		$plotArea->addNew('line_grid', IMAGE_GRAPH_AXIS_X);

		// Make sure background and border not visible (white)
		$plotArea->setBackgroundColor('white');
		$plotArea->setBorderColor('white');

		// Axis config --->

		$XAxis = $plotArea->getAxis(IMAGE_GRAPH_AXIS_X);
		$YAxis = $plotArea->getAxis(IMAGE_GRAPH_AXIS_Y);

		// max & min param
		if (!empty($this->itsOptions['xMax'])) {
			$YAxis->forceMaximum($this->itsOptions['xMax']);
		}
		if (!empty($this->itsOptions['xMin'])) {
			$YAxis->forceMinimum($this->itsOptions['xMin']);
		}
		// display or not X & Y scale unit
		if (!empty($this->itsOptions['xScaleUnit'])) {
			$XAxis->setTitle($this->itsOptions['xScaleUnit']);
		}
		if (!empty($this->itsOptions['yScaleUnit'])) {
			$YAxis->setTitle($this->itsOptions['yScaleUnit']);
		}
	}

	function fetch()
	{
		$this->itsGraph->done();
	}

}


/**
 * tldGraphLine class to construct line graph
 * @package FormsAndReports
 *
 * <code>
 * $graph = new tldGraphLine(array(
 *     'title'=>'Note per Month KPI',
 *     'yScaleUnit'=>'Note',
 *     'xScaleUnit'=>'Month',
 * ));
 * $graph->addLine(
 *     array(
 *         'Jan'=>2,
 *         'Feb'=>3,
 *         'Mar'=>5,
 *         'Apr'=>10,
 *         'May'=>4,
 *         'Jun'=>0
 *     ),
 *     array(
 *         'name'=>'Note for Quality',
 *         'color'=>'blue',
 *     )
 * );
 * $graph->addLine(
 *     array(
 *         'Jan'=>5,
 *         'Feb'=>4,
 *         'Mar'=>2,
 *         'Apr'=>18,
 *         'May'=>5,
 *         'Jun'=>9
 *     ),
 *     array(
 *         'name'=>'Note for Reliability',
 *         'color'=>'green',
 *      'groupTarget'=>5,
 *     )
 * );
 * $graph->fetch();
 *
 * </code>
 *
 * See complete API documentation
 * http://pear.php.net/reference/Image_Graph-latest/li_Image_Graph.html
 */
class tldGraphLine extends tldGraphGeneric
{

	function addLine($data, $options)
	{
		// Check options
		// -- case of group target
		if (!empty($options['groupTarget'])) {
			$groupTargetDataset =& Image_Graph::factory('dataset');
			$groupTargetDataset->setName('Group Target');
		}
		// Create dataset
		$Dataset =& Image_Graph::factory('dataset');
		$Dataset->setName($options['name']);
		// Assign values
		foreach ($data as $k => $v) {
			$Dataset->addPoint($k, $v);
			// case there is group target
			if (!$groupTargetDataset) {
				continue;
			}
			$groupTargetDataset->addPoint($k, $options['groupTarget']);
		}
		// Display line
        $plotArea = Image_Graph::factory('plotarea');
		$Plot =& $plotArea->addNew('Image_Graph_Plot_Line', $Dataset);
        $Plot->setLineColor($options['color']);
		$Marker = Image_Graph::factory('Image_Graph_Marker_Circle');
		$Marker->setSize(3);
		$Marker->setFillColor($options['color']);
        $Plot->setMarker($Marker);

		// Display Group target if applicable
		if ($groupTargetDataset) {
            $Plot =& $this->itsPlotArea->addNew('line', [$groupTargetDataset, 'stacked']);
            $Plot->setLineColor('red');
		}
	}

}


