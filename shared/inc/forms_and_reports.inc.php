/**
 * Courier form
 *
 * @package FormsAndReports
 *
 */
class tldCourier extends basicFormsAndReports
{

	public static $theAllowedCouriers = [
		'UPS', 'FED', 'DHL', 'BAX', 'EMS', 'EXAPAQ',
		'TNT', 'SUR', 'SFE', 'WAT', 'GEFCO', 'AWB', 'BOL',
	];

	function __construct($courier)
	{
		if (in_array(strtoupper($courier), self::$theAllowedCouriers)) {
			$this->itsID = strtoupper($courier);
		}
	}

	function isEmpty()
	{
		return empty($this->itsID);
	}

	public static function getList()
	{
		return self::$theAllowedCouriers;
	}

	public static function parseMultiple($text)
	{
		$lines = explode("\n", $text);
		foreach ($lines as $line) {
			if (empty($line)) {
				continue;
			}
			$data = explode('#', trim($line));
			$courier = strtoupper($data[0]);
			$trackNum = $data[1];
			if (!in_array($courier, self::$theAllowedCouriers)) {
				$courier = '';
				$trackNum = $line;
			}
			$result[] = ['courier' => $courier, 'trackNum' => $trackNum];
		}
		return $result;
	}

	public static function outMultiple($text)
	{
		$result = '';
		$lines = self::parseMultiple($text);
		if (count($lines ?? []) > 0) {
			foreach ($lines as $line) {
				$courier = new tldCourier($line['courier']);
				$result .= $courier->fetch($line['trackNum']);
			}
			return $result;
		}
	}

	function fetch($trackNum = null)
	{
		if ($this->itsID) {
			$smarty = $this->getSmarty();
			$smarty->assign('trackNum', $trackNum);
			$trackID = strtolower($this->itsID);
			return $smarty->fetch($this->itsTPLPath . '/tldCourier/' . $trackID . '.inc.tpl');
		}

		return $trackNum;
	}
}

/**
