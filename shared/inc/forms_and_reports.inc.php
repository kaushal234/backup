class tldReportMultiLevel extends basicFormsAndReports
{
	public $itsTitle;
	public $itsData;
	public $itsFields;
	public $itsOptions;

	function __construct($data, $fields, $columns, $options = '')
	{
		$this->itsData = $data;            //array of data rows
		$this->itsFields = $fields;        //fields to split on
		$this->itsColumns = $columns;    //columns to display at last level
		$this->itsOptions = $options;
	}

	/**
	 * return the MultiLevel Report
	 *
	 * @return string
	 */
	function fetch()
	{
		$result = '<h3>' . $this->itsOptions['title'] . '</h3>';
		//get the table
		$suffix = isset($this->itsOptions['menu_suffix']) ? $this->itsOptions['menu_suffix'] : '';
		$table = $this->groupRec($this->itsData, $this->itsFields, 0, $suffix);

		//if nothing in $table then don't even print the header!!
		if (empty($table)) {
			$result .= '<p>No results found...</p>';
			return $result;
		}

		// Form for quick access in listing using first field
		$result .= $this->fetchIndex($this->createIndex($this->itsData, $this->itsFields[0]), $suffix) . '';

		$result .= '<table width="100%">';
		$result .= '<tr bgcolor="#d0d0d0"><td>&nbsp;</td>';
		foreach ($this->itsColumns as $key => $label) {
			$result .= "<th>{$label}</th>";
		}
		$functions = isset($this->itsOptions['functions']) ? $this->itsOptions['functions'] : [];
		foreach ($functions as $header => $values) {
			$result .= "<th style=\"text-align: center\">{$header}</th>";
		}
		$result .= '</tr>';
		$result .= $table;
		$result .= '&nbsp;</tr></table>';
		if (!empty($this->itsOptions['showGrandTotalRows'])) {
			$result .= '<b>Total rows=' . count($this->itsData) . '</b>';
		}
		return $result;
	}

	function groupRec($rows, $fields, $level = 0, $suffix = '')
	{
		$smarty = $this->getSmarty();
		if ($level >= count($fields ?? [])) {
			$smarty->assign('rows', $rows);
			$smarty->assign('columns', $this->itsColumns);
			$smarty->assign('options', $this->itsOptions);
			$smarty->assign('level', $level);
			return '</td></tr>' . $smarty->fetch($this->itsTPLPath . '/tldReportMultiLevel.tpl') .
				'<tr><td colspan="' . (count($this->itsColumns) + 1) . '">';
		}
		if (count($rows ?? [])) {
			foreach ($rows as $row) {
				$data[$row[$fields[$level]]][] = $row;
			}
			$result = '';
			foreach ($data as $key => $value) {
				if ($level == 0) {
					$keyParsed = trim($key);
					$result .= '<tr><td colspan="' . (count($this->itsColumns) + 1) . "\"><a id=\"{$keyParsed}{$suffix}\" name=\"$keyParsed\"><b>$keyParsed</b></a>";
					if (!empty($this->itsOptions['showNumberOfRowsByLevel'])) {
						if (in_array($level, $this->itsOptions['showNumberOfRowsByLevel'])) {
							$result .= ' - Total of ' . count($value) . ' rows';
						}
					}
					$result .= '<br>';
				} else {
					for ($i = 0; $i < $level; $i++) {
						$result .= '&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;';
					}
					$result .= "<b>$key";
					if (!empty($this->itsOptions['showNumberOfRowsByLevel'])) {
						if (in_array($level, $this->itsOptions['showNumberOfRowsByLevel'])) {
							$result .= ' - Total of ' . count($value) . ' rows';
						}
					}
					$result .= '</b><br>';
				}
				$result .= $this->groupRec($value, $fields, $level + 1, $suffix);
			}
		}
		return $result ?? [];
	}
}

