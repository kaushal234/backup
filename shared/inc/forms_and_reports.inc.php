	{
		global $sess;
		$this->itsModule = $module;
		$this->itsData = $data;
		$this->itsColumns = $xItems;
		$this->itsOptions = $options;
		$this->itsOrder = [];
		#$this->groupedHeaders = array();
		$this->itsHeaders = [];
		$this->date = mktime(0, 0, 0, date('m'), date('d'), date('Y'));

		if (!isset($sess[$this->itsModule]['gantt'])) {
			$sess[$this->itsModule]['gantt'] = [];
		}
		$this->sess =& $sess[$this->itsModule]['gantt'];

		$this->sort();
		$this->prepare();
	}

	/**
	 * Prepare options for chart display
	 */
	function prepare()
	{
		foreach (array_keys($this->itsColumns) AS $field) {
			// Set defaults
			if (isset($this->itsOptions['columnSettings'][$field]['type'])) {
				$settings = $this->itsOptions['columnSettings'][$field];
				switch ($this->itsOptions['columnSettings'][$field]['type']) {
					case 'gantt':
						if (isset($settings['rangeBack']) OR isset($settings['rangeForward'])) {
							$settings['rangeBack'] = (isset($settings['rangeBack'])) ? ($settings['rangeBack'] > 0) ? (int)$settings['rangeBack'] : 0 : 6;
							$settings['rangeForward'] = (isset($settings['rangeForward'])) ? ($settings['rangeForward'] > 0) ? (int)$settings['rangeForward'] : 0 : 6;
							$tics = range(-$settings['rangeBack'], +$settings['rangeForward']);
						} else {
							$settings['range'] = (isset($settings['range'])) ? ($settings['range'] > 0) ? (int)$settings['range'] : 0 : 6;
							$tics = range(-$settings['range'], +$settings['range']);
						}
						$settings['zoom'] = (in_array($settings['zoom'], ['day', 'week', 'month'])) ? $settings['zoom'] : 'month';
						foreach ($tics AS $tic) {
							$a = strtotime("$tic {$settings['zoom']}", $this->date);

							$settings['tics'][] = [
								'title' => ($settings['ticDateFormat']) ? date($settings['ticDateFormat'], $a) : $tic,
								'tic' => $tic,
							];

							switch ($settings['zoom']) {
								case 'day':
									$b = mktime(23, 59, 59, date('m', $a), date('d', $a), date('Y', $a));
									break;
								case 'week':
									$a = mktime(0, 0, 0, date('m', $a), date('d', $a) - date('N', $a) + 1, date('Y', $a));
									$b = mktime(23, 59, 59, date('m', $a), date('d', $a) + 6, date('Y', $a));
									break;
								case 'month':
									$a = mktime(0, 0, 0, date('m', $a), 1, date('Y', $a));
									$b = mktime(23, 59, 59, date('m', $a) + 1, 0, date('Y', $a));
									break;
							}
							$settings['offset'][$tic] = ['A' => $a, 'B' => $b];
							if ($settings['subgroup']) {
								$settings['subgroupDateFormat'] = $settings['subgroupDateFormat'] ? $settings['subgroupDateFormat'] : 'Y';
								$settings['subgroups'][date($settings['subgroupDateFormat'], $a)][] = $tic;
							}
						}
						break;
				}
				$this->itsOptions['columnSettings'][$field] = $settings;
			}
		}

		// PREPARE HEADER & COLUMN ORDER
		foreach ($this->itsColumns AS $field => $title) {
			if (in_array($field, $this->itsOrder)) {
				continue;
			}
			if (in_array($this->itsOptions['columnSettings'][$field]['type'], ['gantt'])) {
				$columns = [];
				foreach ((array)$this->itsOptions['columnSettings'][$field]['tics'] AS $header) {
					$columns[] = [
						'title' => $header['title'],
						'tic' => $header['tic'],
						'field' => $field,
					];
				}
				$this->itsHeaders[] = [
					'field' => $field,
					'subgrouped' => ($this->itsOptions['columnSettings'][$field]['subgroup']) ? true : false,
					'grouped' => true,
					'title' => $title,
					'attributes' => $this->itsOptions['columnSettings'][$field]['thAttributes'],
					'columns' => $columns,
				];
				$this->itsOrder[] = $field;
				continue;
			}

			foreach ((array)$this->itsOptions['groupHeaders'] AS $group) {
				if (in_array($field, (array)$group['columns'])) {
					$columns = [];
					foreach ($this->itsColumns AS $field => $header) {
						if (in_array($this->itsOptions['columnSettings'][$field]['type'], ['gantt'])) {
							continue;
						}
						if (in_array($field, (array)$group['columns']) AND !in_array($field, $this->itsOrder)) {
							$columns[] = [
								'title' => $header,
								'field' => $field,
							];
							$this->itsOrder[] = $field;
						}
					}
					$this->itsHeaders[] = [
						'field' => $field,
						'grouped' => true,
						'title' => $group['title'],
						'attributes' => $group['thAttributes'],
						'columns' => $columns,
					];
					continue 2;
				}
			}

			if (!in_array($field, $this->itsOrder)) {
				$this->itsHeaders[] = [
					'field' => $field,
					'columns' => [[
						'title' => $title,
						'field' => $field,
					]],
				];
				$this->itsOrder[] = $field;
			}
		}

		// PREPARE DATA
		if (!empty($this->itsOptions['columnSettings'])) {
			foreach ($this->itsData AS &$row) {
				foreach ($this->itsOptions['columnSettings'] AS $field => $settings) {
					if (array_key_exists($field, $row) && !empty($settings['callback'])) {
						$row[$field] = call_user_func($settings['callback'], $row[$field]);
					}
				}
			}
		}
	}

	/**
	 * Fetch html string of chart
	 * @return    string
	 */
	function fetch()
	{
		global $php_self;
		ob_start();
		include($this->itsTPLPath . '/tldGanttChart.tpl.php');
		$html = ob_get_contents();
		ob_end_clean();
		return $html;
	}

	/**
	 * Sort data list by column field, by last sort method or by REQUEST value
	 * or stored session sort field
	 * @param string $field Field name to sort
	 */
	function sort($field = null)
	{
		if ($field === null) {
			if (isset($_REQUEST['sort'])) {
				$this->sort($_REQUEST['sort']);
			} else {
				if ($this->sess['sort']) {
					usort($this->itsData, [$this, '_usort']);
				}
			}
		} elseif (array_key_exists($field, $this->itsData[0])) {
			if ($field == $this->sess['sort']) {
				$this->sess['order'] = ($this->sess['order'] === 'asc') ? 'desc' : 'asc';
			} else {
				$this->sess['sort'] = $field;
				$this->sess['order'] = 'asc';
			}
			usort($this->itsData, [$this, '_usort']);
		} else {
			// Do nothing
		}
	}

	/**
	 * Internal user method for comparing the sort order of each row
	 * @param array $a
	 * @param array $b
	 * @return    integer
	 */
	function _usort($a, $b)
	{
		if (is_numeric($a[$this->sess['sort']]) AND is_numeric($b[$this->sess['sort']])) {
			$compare = ($a[$this->sess['sort']] == $b[$this->sess['sort']]) ? 0 : (($a[$this->sess['sort']] > $b[$this->sess['sort']]) ? 1 : -1);
		} else {
			$compare = strcmp($a[$this->sess['sort']], $b[$this->sess['sort']]);
		}
		return ($this->sess['order'] === 'desc') ? -$compare : $compare;
	}

	/**
	 * Format string with escaped values
	 * @param string $string Input String
	 * @param string $replace,... unlimited OPTIONAL Replace format
	 * @return    string
	 */
	function strFormat($string)
	{
		$arguments = array_filter(array_slice(func_get_args(), 1));
        $arguments = array_map('trim', $arguments);
        return trim(vsprintf($string ?? '', $arguments));
	}

	/**
	 * Convert to html entities
	 * @param string $string Input string
	 * @param string $default Default value if input is empty
	 * @return    string
	 */
	function toHtml($string, $default = '&nbsp;')
	{
		$string = trim($string ?? '');
		return ($string != '') ? tldUtils::isohtmlspecialchars($string) : $default;
	}

	/**
	 * Merges multiple attributes into an html ready tag string
	 * @param array|string $attributes HTML Tag Attributes
	 * @param array|string $attributes,... unlimited OPTIONAL Tag attributes that will override matched attributes on the left
	 * @return    string
	 */
	function setAttributes($attributes)
	{
		$parameters = func_get_args();
		$attributes = $output = [];

		foreach ($parameters AS $param) {
			if (empty($param)) {
				continue;
			}
			if (is_string($param)) {
				$attributes = array_merge($attributes, $this->attrArray($param));
			} elseif (is_array($param)) {
				$attributes = array_merge($attributes, $param);
			}
		}
		$attributes = array_change_key_case(array_map('trim', $attributes), CASE_LOWER);
		foreach ($attributes AS $key => $value) {
			if (!empty($key)) {
				$output[trim($key)] = trim($key) . '="' . $this->toHtml($value, '') . '"';
			}
		}
		return (count($output) > 0) ? ' ' . implode(' ', $output) : '';
	}

	function attrArray($string)
	{
		$attributes = [];
		try {
			$string =  mb_convert_encoding($string, 'UTF-8', mb_list_encodings());
			$x = new SimpleXMLElement("<element $string />");
			$attr = $x->attributes();
			foreach ($attr AS $key => $value) {
				$attributes[(string)$key] = (string)$value;
			}
		} catch (Exception $e) {
		}
		return $attributes;
	}

	/**
	 * Checks if group headers exist
	 * @return    boolean
	 */
	function hasGroupHeaders()
	{
		foreach ($this->itsHeaders AS $header) {
			if ($header['grouped']) {
				return true;
			}
		}
		return false;
	}

	/**
	 * Checks if subgroup headers exist
	 * @return    boolean
	 */
	function hasSubGroupHeaders()
	{
		foreach ($this->itsHeaders AS $header) {
			if ($header['subgrouped']) {
				return true;
			}
		}
		return false;
	}

	/**
	 * Check if integer is between start and end range
	 * @param integer $integer
	 * @param integer $start
	 * @param integer $end
	 * @return    boolean
	 */
	function between($integer, $start, $end)
	{
		return ($integer >= $start AND $integer <= $end) ? true : false;
	}
}

class tldPagination extends basicFormsAndReports
{
	public $itsInstance;
	public $itsData;
	public $itsPage;
	public $itsLimit;
	public $itsDisplay;

	function __construct($instance_name, $rows, $limit = 10)
	{
		global $sess;
		$this->itsInstance =& $sess['pagination'][$instance_name];
		$this->itsData = $rows;
		$this->itsLimit = $limit;
		$this->itsPage = $this->getPage();
		$this->itsDisplay = $this->getDisplay();
		$this->itsInstance = [
			'name' => $instance_name,
			'page' => $this->itsPage,
			'show' => $this->itsDisplay,
		];
	}

	function getPage()
	{
		if (!empty($this->itsPage)) {
			return $this->itsPage;
		}
		// Set default page
		$page = 1;
		// Set page from stored session
		if ($this->itsInstance['page']) {
			$page = $this->itsInstance['page'];
		}
		// Set page number if passed in request
		if (is_numeric($_REQUEST['page'])) {
			$page = (int)$_REQUEST['page'];
		}
		// Set navigation keywords for page number
		switch ($_REQUEST['page']) {
			case 'first':
				$page = 1;
				break;
			case 'prev':
				--$page;
				break;
			case 'next':
				++$page;
				break;
			case 'last':
				$page = $this->getPageCnt();
				break;
		}
		// Only allow min/max page count
		if ($page < 1) {
			$page = 1;
		} elseif ($page > $this->getPageCnt()) {
			$page = $this->getPageCnt();
		}
		return $page;
	}

	function getDisplay()
	{
		if (!empty($this->itsDisplay)) {
			return $this->itsDisplay;
		}
		// Set default display
		$display = 'less';
		// Set display from stored session
		if ($this->itsInstance['show']) {
			$display = $this->itsInstance['show'];
		}
		// Set display from request
		switch ($_REQUEST['page']) {
			case 'all':
				$display = 'all';
				break;
			case 'less':
				$display = 'less';
				break;
		}
		return $display;
	}

	function getPageCnt()
	{
		if (!$this->getDataCnt()) {
			return 1;
		}
		$pages = $this->getDataCnt() / $this->itsLimit;
		return ceil($pages);
	}

	function getDataCnt()
	{
		return count($this->itsData);
	}

	function getData()
	{
		if ($this->itsDisplay === 'all') {
			return $this->itsData;
		}
		$chunked = [];
		$page = $line = 1;
		foreach ($this->itsData AS $value) {
			if ($page == $this->itsPage) {
				$chunked[] = $value;
			}
			if ($line % $this->itsLimit === 0) {
				$page++;
			}
			$line++;
		}
		return $chunked;
	}

	function getCntString()
	{
		if (!$this->getDataCnt()) {
			return 'No results';
		}
		if ($this->itsDisplay === 'all') {
			return '';
		}
		return "Page {$this->itsPage} of {$this->getPageCnt()} ({$this->getDataCnt()} results)";
	}

	function getNavLinks($url, $show_jumpto = true, $show_toggle = true)
	{
		$parts = explode('?', $url);
		parse_str($parts[1], $params);
		unset($params['page']);
		$url = $parts[0] . '?';
		if (count($params) > 0) {
			$url .= http_build_query($params) . '&';
		}
		$options = [
			'show_jumpto' => $show_jumpto,
			'show_toggle' => $show_toggle,
		];

		$smarty = $this->getSmarty();
		$smarty->assign('pg_url', $url);
		$smarty->assign('pg_options', $options);
		$smarty->assign('pg_object', $this);
		return $smarty->fetch($this->itsTPLPath . '/tldPagination.tpl');
	}
}

