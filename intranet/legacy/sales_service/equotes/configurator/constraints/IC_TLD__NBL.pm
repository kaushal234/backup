      "origname" => "M002",
      "globals" => $globals,
      "features" => $features,
      };

  bless $self,$class;
  return $self;
}

sub before_input
{
  my $self = shift;
}

sub validation
{
  my $self = shift;
  my $s_validate = $self->{globals}->getInteger("validate");

  my $f_CONFIG = $self->{features}->getString("CONFIG");

  if( !(($f_CONFIG eq "NBL_EL")) ) {
    $s_validate = 0;
  }

  $self->{globals}->set("validate", $s_validate);
}

