sub validation
{
  my $self = shift;
  my $s_validate = $self->{globals}->getInteger("validate");

  my $f_SPAREWHL = $self->{features}->getString("SPAREWHL");
  my $f_BALLAST = $self->{features}->getString("BALLAST");

  if( !(($f_SPAREWHL eq "Y")) ) {
    $s_validate = 0;
  }
  if( !(($f_BALLAST eq "15")) ) {
    $s_validate = 0;
  }

  $self->{globals}->set("validate", $s_validate);
}

